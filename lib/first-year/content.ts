export function validMonth(value: unknown): number {
  return typeof value === "number" &&
    Number.isInteger(value) &&
    value >= 0 &&
    value <= 12
    ? value
    : 0;
}
// Approximate chapter navigation only; never infer a child's age or ability.
export function chapterForPosition(
  value: number,
  unit: "day" | "week",
): number {
  const maximum = unit === "day" ? 365 : 53;
  if (!Number.isInteger(value) || value < 1 || value > maximum) return 0;
  const day = unit === "day" ? value : Math.min(365, (value - 1) * 7 + 1);
  return day === 365 ? 12 : Math.min(11, Math.floor((day - 1) / (365 / 12)));
}
export function validReadMonths(value: unknown): number[] {
  return Array.isArray(value)
    ? [
        ...new Set(
          value.filter(
            (v): v is number =>
              typeof v === "number" && Number.isInteger(v) && v >= 0 && v <= 12,
          ),
        ),
      ].sort((a, b) => a - b)
    : [];
}
